-- ════════════════════════════════════════════════════════════════════════════
--  Dawat Biryani House — V3: live customer ↔ admin chat + coupon safety.
--  ADDITIVE: new tables/functions/triggers only. Changes to existing objects: the notifications.kind CHECK is
--  widened (adds 'new_chat'), one nullable column is added to notifications, and a trigger stops a USED coupon
--  from being hard-deleted (it must be archived, so old bills stay explained). No existing data is touched.
--  Customer identity = a random secret token kept on the customer's device; only its SHA-256 is stored.
--  Customers can reach ONLY their own conversation through SECURITY DEFINER functions (no table grants to anon).
-- ════════════════════════════════════════════════════════════════════════════

create table if not exists public.chat_settings (
  id int primary key default 1 check (id = 1),
  enabled boolean not null default true,
  admin_online boolean not null default false,
  admin_seen_at timestamptz,
  welcome_message text not null default 'Namaste! Welcome to Dawat Biryani House. How can we help you today?' check (char_length(welcome_message) <= 300),
  offline_message text not null default 'We are offline right now. Leave your message and we will reply as soon as we are back. For urgent orders please call us.' check (char_length(offline_message) <= 300),
  retention_days int not null default 180 check (retention_days between 7 and 3650),
  updated_at timestamptz not null default now()
);
insert into public.chat_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.chat_conversations (
  id uuid primary key,                                   -- generated by the customer's browser (idempotent retries)
  token_hash text not null,                              -- sha256 hex of the customer's secret token
  customer_name text check (char_length(customer_name) <= 60),
  status text not null default 'open' check (status in ('open','resolved','archived')),
  admin_unread int not null default 0 check (admin_unread >= 0),
  customer_unread int not null default 0 check (customer_unread >= 0),
  last_message_at timestamptz not null default clock_timestamp(),
  last_message_preview text not null default '',
  client_fp bytea,                                       -- daily-salted IP hash, abuse limits only
  created_at timestamptz not null default clock_timestamp()
);
create index if not exists chat_conv_last_idx on public.chat_conversations (last_message_at desc);
create index if not exists chat_conv_fp_idx on public.chat_conversations (client_fp, created_at desc) where client_fp is not null;

create table if not exists public.chat_messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.chat_conversations(id) on delete cascade,
  sender text not null check (sender in ('customer','admin','system')),
  kind text check (kind in ('welcome','offline')),
  body text not null check (char_length(body) between 1 and 1000),
  client_msg_id uuid,
  read_at timestamptz,
  created_at timestamptz not null default clock_timestamp(),
  unique (conversation_id, client_msg_id)               -- the same message can never be stored twice
);
create index if not exists chat_msg_conv_idx on public.chat_messages (conversation_id, created_at);

alter table public.notifications add column if not exists conversation_id uuid references public.chat_conversations(id) on delete cascade;
alter table public.notifications drop constraint if exists notifications_kind_check;
alter table public.notifications add constraint notifications_kind_check check (kind in ('new_order','order_update','new_bulk','new_enquiry','new_chat'));

-- ───────────────────────── helpers (not callable from the API) ─────────────────────────
create or replace function public._chat_online() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select s.enabled and s.admin_online and s.admin_seen_at > now() - interval '5 minutes' from public.chat_settings s where s.id = 1), false)
$$;

create or replace function public._chat_purge() returns int
language plpgsql security definer set search_path = '' as $$
declare n int;
begin
  delete from public.chat_conversations c
   where c.last_message_at < now() - make_interval(days => (select retention_days from public.chat_settings where id = 1));
  get diagnostics n = row_count;
  return n;
end $$;

create or replace function public._chat_payload(p_conv uuid, p_mark_read boolean) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare c public.chat_conversations; v jsonb;
begin
  select * into c from public.chat_conversations where id = p_conv;
  if not found then return jsonb_build_object('not_found', true); end if;
  if p_mark_read and c.customer_unread > 0 then
    update public.chat_messages set read_at = now() where conversation_id = p_conv and sender <> 'customer' and read_at is null;
    update public.chat_conversations set customer_unread = 0 where id = p_conv returning * into c;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('id', m.id, 'cid', m.client_msg_id, 'sender', m.sender, 'kind', m.kind, 'body', m.body, 'created_at', m.created_at) order by m.created_at, m.id), '[]'::jsonb)
    into v from (select * from public.chat_messages where conversation_id = p_conv order by created_at desc, id desc limit 300) m;
  return jsonb_build_object('status', c.status, 'unread', c.customer_unread, 'messages', v,
                            'online', public._chat_online(), 'enabled', (select enabled from public.chat_settings where id = 1));
end $$;

-- ───────────────────────── customer API ─────────────────────────
create or replace function public.chat_status() returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('enabled', s.enabled, 'online', public._chat_online(), 'welcome_message', s.welcome_message, 'offline_message', s.offline_message)
    from public.chat_settings s where s.id = 1
$$;

create or replace function public.chat_send(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  s public.chat_settings; c public.chat_conversations; v_conv uuid; v_tok text; v_hash text; v_body text; v_cid uuid; v_name text;
  v_fp bytea; v_ip text; v_n int; v_mid uuid; v_was int; v_new boolean := false;
begin
  select * into s from public.chat_settings where id = 1;
  if not s.enabled then raise exception 'chat_disabled' using errcode = 'P0001', hint = 'Live chat is not available right now. Please call us.'; end if;
  begin v_conv := (p ->> 'conversation_id')::uuid; v_cid := (p ->> 'client_id')::uuid;
  exception when others then raise exception 'invalid_request' using errcode = '22023'; end;
  v_tok := coalesce(p ->> 'token', '');
  v_body := btrim(coalesce(p ->> 'body', ''));
  v_name := nullif(btrim(left(coalesce(p ->> 'name', ''), 60)), '');
  if v_conv is null or v_cid is null or char_length(v_tok) < 32 or char_length(v_tok) > 200 then raise exception 'invalid_request' using errcode = '22023'; end if;
  if char_length(v_body) < 1 or char_length(v_body) > 1000 then
    raise exception 'chat_invalid' using errcode = 'P0001', hint = 'Please type a message (up to 1000 characters).';
  end if;
  v_hash := encode(sha256(convert_to(v_tok, 'UTF8')), 'hex');
  begin
    v_ip := btrim(split_part(coalesce(nullif(current_setting('request.headers', true), '')::json ->> 'x-forwarded-for', ''), ',', 1));
  exception when others then v_ip := ''; end;
  if coalesce(v_ip, '') <> '' then v_fp := sha256(convert_to(v_ip || '|' || current_date::text || '|dawat-chat', 'UTF8')); end if;

  select * into c from public.chat_conversations where id = v_conv for update;
  if not found then
    if v_fp is not null then
      select count(*) into v_n from public.chat_conversations where client_fp = v_fp and created_at > now() - interval '1 hour';
      if v_n >= 5 then raise exception 'rate_limited' using errcode = 'P0001', hint = 'Too many chats from this device. Please try again later or call us.'; end if;
    end if;
    select count(*) into v_n from public.chat_conversations where created_at > now() - interval '1 hour';
    if v_n >= 300 then raise exception 'rate_limited' using errcode = 'P0001', hint = 'Chat is very busy. Please call us.'; end if;
    insert into public.chat_conversations (id, token_hash, customer_name, client_fp) values (v_conv, v_hash, v_name, v_fp) returning * into c;
    v_new := true;
    if s.welcome_message <> '' then
      insert into public.chat_messages (conversation_id, sender, kind, body) values (v_conv, 'system', 'welcome', s.welcome_message);
    end if;
    perform public._chat_purge();
  elsif c.token_hash <> v_hash then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  select count(*) into v_n from public.chat_messages where conversation_id = v_conv and sender = 'customer' and created_at > now() - interval '1 minute';
  if v_n >= 15 then raise exception 'rate_limited' using errcode = 'P0001', hint = 'You are sending messages too quickly. Please wait a moment.'; end if;

  insert into public.chat_messages (conversation_id, sender, body, client_msg_id) values (v_conv, 'customer', v_body, v_cid)
  on conflict (conversation_id, client_msg_id) do nothing returning id into v_mid;

  if v_mid is not null then                                -- a genuinely new message (not a retry)
    v_was := c.admin_unread;
    update public.chat_conversations set admin_unread = admin_unread + 1, last_message_at = clock_timestamp(),
           last_message_preview = left(v_body, 120), status = 'open', customer_name = coalesce(customer_name, v_name)
     where id = v_conv;
    if v_was = 0 then                                       -- one notification per "unread streak", never one per message
      insert into public.notifications (event_key, kind, title, body, conversation_id)
      values ('chat:' || v_mid, 'new_chat', 'New chat message', coalesce(c.customer_name, v_name, 'Visitor') || ': ' || left(v_body, 80), v_conv)
      on conflict (event_key) do nothing;
    end if;
    if not public._chat_online() and s.offline_message <> '' and not exists (
         select 1 from public.chat_messages where conversation_id = v_conv and kind = 'offline' and created_at > now() - interval '30 minutes') then
      insert into public.chat_messages (conversation_id, sender, kind, body) values (v_conv, 'system', 'offline', s.offline_message);
    end if;
  end if;
  return public._chat_payload(v_conv, true);
end $$;

create or replace function public.chat_fetch(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare v_conv uuid; v_tok text; c public.chat_conversations;
begin
  begin v_conv := (p ->> 'conversation_id')::uuid; exception when others then raise exception 'invalid_request' using errcode = '22023'; end;
  v_tok := coalesce(p ->> 'token', '');
  select * into c from public.chat_conversations where id = v_conv;
  if not found then return jsonb_build_object('not_found', true); end if;
  if c.token_hash <> encode(sha256(convert_to(v_tok, 'UTF8')), 'hex') then raise exception 'forbidden' using errcode = '42501'; end if;
  return public._chat_payload(v_conv, coalesce((p ->> 'mark_read')::boolean, false));
end $$;

-- ───────────────────────── admin API ─────────────────────────
create or replace function public.admin_chat_reply(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare v_conv uuid; v_cid uuid; v_body text; v_mid uuid;
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  begin v_conv := (p ->> 'conversation_id')::uuid; v_cid := (p ->> 'client_id')::uuid; exception when others then raise exception 'invalid_request' using errcode = '22023'; end;
  v_body := btrim(coalesce(p ->> 'body', ''));
  if char_length(v_body) < 1 or char_length(v_body) > 1000 then raise exception 'chat_invalid' using errcode = 'P0001', hint = 'Type a reply (up to 1000 characters).'; end if;
  perform 1 from public.chat_conversations where id = v_conv for update;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  insert into public.chat_messages (conversation_id, sender, body, client_msg_id) values (v_conv, 'admin', v_body, v_cid)
  on conflict (conversation_id, client_msg_id) do nothing returning id into v_mid;
  if v_mid is not null then
    update public.chat_conversations set customer_unread = customer_unread + 1, admin_unread = 0, status = 'open',
           last_message_at = clock_timestamp(), last_message_preview = 'You: ' || left(v_body, 110) where id = v_conv;
    update public.chat_messages set read_at = now() where conversation_id = v_conv and sender = 'customer' and read_at is null;
  end if;
  return jsonb_build_object('id', v_mid, 'duplicate', v_mid is null);
end $$;

create or replace function public.admin_chat_action(p jsonb) returns void
language plpgsql volatile security definer set search_path = '' as $$
declare v_conv uuid := (p ->> 'conversation_id')::uuid; v_a text := p ->> 'action';
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  if v_a not in ('read','resolve','reopen','archive','unarchive','delete') then raise exception 'invalid_request' using errcode = '22023'; end if;
  if v_a = 'delete' then delete from public.chat_conversations where id = v_conv;
  elsif v_a = 'read' then
    update public.chat_conversations set admin_unread = 0 where id = v_conv;
    update public.chat_messages set read_at = now() where conversation_id = v_conv and sender = 'customer' and read_at is null;
  else
    update public.chat_conversations set status = case v_a when 'resolve' then 'resolved' when 'archive' then 'archived' else 'open' end,
           admin_unread = case when v_a in ('resolve','archive') then 0 else admin_unread end where id = v_conv;
  end if;
end $$;

create or replace function public.admin_chat_heartbeat() returns void
language plpgsql volatile security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  update public.chat_settings set admin_seen_at = now() where id = 1;
end $$;

create or replace function public.admin_chat_purge() returns int
language plpgsql volatile security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  return public._chat_purge();
end $$;

-- ───────────────────────── security: RLS + grants ─────────────────────────
alter table public.chat_settings enable row level security;
alter table public.chat_conversations enable row level security;
alter table public.chat_messages enable row level security;

create policy "admin manages chat settings" on public.chat_settings for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin reads conversations" on public.chat_conversations for select to authenticated using (public.is_admin());
create policy "admin reads messages" on public.chat_messages for select to authenticated using (public.is_admin());

revoke all on public.chat_settings, public.chat_conversations, public.chat_messages from anon, authenticated;
grant select, update on public.chat_settings to authenticated;
-- the secret token hash and the abuse fingerprint are never readable through the API
grant select (id, customer_name, status, admin_unread, customer_unread, last_message_at, last_message_preview, created_at) on public.chat_conversations to authenticated;
grant select on public.chat_messages to authenticated;

revoke all on function public._chat_online(), public._chat_purge(), public._chat_payload(uuid, boolean) from public, anon, authenticated;
revoke all on function public.chat_status(), public.chat_send(jsonb), public.chat_fetch(jsonb) from public;
grant execute on function public.chat_status(), public.chat_send(jsonb), public.chat_fetch(jsonb) to anon, authenticated;
revoke all on function public.admin_chat_reply(jsonb), public.admin_chat_action(jsonb), public.admin_chat_heartbeat(), public.admin_chat_purge() from public, anon;
grant execute on function public.admin_chat_reply(jsonb), public.admin_chat_action(jsonb), public.admin_chat_heartbeat(), public.admin_chat_purge() to authenticated;

-- ───────────────────────── realtime ─────────────────────────
-- Admin dashboard: Postgres Changes on chat_messages (RLS: admins only). chat_conversations is NOT published
-- (it has column-level grants; the admin panel reloads the list whenever a message event arrives).
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'chat_messages') then
      alter publication supabase_realtime add table public.chat_messages;
    end if;
  end if;
end $$;

-- Customer widget: when the restaurant (or the auto-reply) writes into a conversation, a content-free
-- "changed" ping is broadcast on the public topic chat:<conversation id>. The widget then re-reads the
-- conversation through chat_fetch with its secret token, so the ping itself reveals nothing. If Realtime is
-- unavailable the insert still succeeds (the ping is best-effort) and the widget's polling delivers the reply.
create or replace function public._chat_after_message() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.sender <> 'customer' then
    begin
      perform realtime.send(jsonb_build_object('at', clock_timestamp()), 'changed', 'chat:' || new.conversation_id::text, false);
    exception when others then null;
    end;
  end if;
  return null;
end $$;
revoke all on function public._chat_after_message() from public, anon, authenticated;
create or replace trigger chat_messages_push after insert on public.chat_messages for each row execute function public._chat_after_message();

-- ───────────────────────── coupons: a used coupon is archived, never erased ─────────────────────────
create or replace function public._offer_before_delete() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if old.used_count > 0 or exists (select 1 from public.offer_redemptions r where r.offer_id = old.id) then
    raise exception 'offer_used' using errcode = 'P0001',
      hint = 'This coupon has already been used on orders, so it cannot be deleted. Archive it instead — old bills stay correct.';
  end if;
  return old;
end $$;
revoke all on function public._offer_before_delete() from public, anon, authenticated;
create or replace trigger offers_before_delete before delete on public.offers for each row execute function public._offer_before_delete();
